-- Міграція 029: роль «Адміністратор Підрозділу» (код unit_admin).
--
-- Повний доступ до даних і користувачів СВОГО організаційного підрозділу (AD OU чи підрозділ локального користувача — міграція 030, разом із вкладеними):
-- проєкти, задачі, тікети, звіти людей з підрозділу; керування користувачами підрозділу.
-- Налаштування системи, Active Directory, API, журнал аудиту — недоступні (лише «Адміністратор системи»).
--
-- На новій інсталяції (seed.sql "з нуля") роль уже включена, міграція не потрібна.
--
-- Застосування:
--   mysql -u root -p --default-character-set=utf8mb4 ІМ_Я_БД < database/migrations/029_add_unit_admin_role.sql
--
-- Скрипт безпечний для повторного запуску.

INSERT INTO roles (code, name, description)
SELECT 'unit_admin', 'Адміністратор Підрозділу',
       'Повний доступ до даних і користувачів власного організаційного підрозділу (AD OU)'
WHERE NOT EXISTS (SELECT 1 FROM roles WHERE code = 'unit_admin');
