<?php

namespace App\Core;

/**
 * Навігація ролі «Адміністратор Підрозділу» — той самий вигляд, що в адміністратора системи (App\Core\AdminNav):
 * дві вкладки-розділи зі сторінками-хабами з картками й посиланням «назад» на підсторінках.
 *
 *   «Керування»            (/unit/manage)   — проєкти, задачі, тікети, канбан, Гант, облік часу, черги, CSAT підрозділу;
 *   «Налаштування системи» (/unit/settings) — користувачі й журнал аудиту підрозділу.
 *
 * Тут єдине місце, де записано, яка сторінка до якого розділу належить.
 */
class UnitNav
{
    public const SECTIONS = [
        'manage' => [
            'title' => 'Керування',
            'heading' => 'Керування проєктами, задачами й тікетами підрозділу',
            'lead' => 'Усе, що стосується роботи вашого підрозділу: проєкти, задачі, тікети, канбан, Гант, облік часу, черги й якість обслуговування.',
            'url' => '/unit/manage',
            'prefixes' => ['/unit/manage', '/unit/projects', '/unit/board', '/unit/gantt', '/unit/time', '/unit/queues', '/unit/csat'],
        ],
        'settings' => [
            'title' => 'Налаштування системи',
            'heading' => 'Налаштування системи',
            'lead' => 'Користувачі підрозділу та контроль їхніх дій у системі.',
            'url' => '/unit/settings',
            'prefixes' => ['/unit/settings', '/unit/users', '/unit/audit'],
        ],
    ];

    /** Розділ за шляхом запиту; null — це не сторінка розділів підрозділу. */
    public static function sectionForPath(string $path): ?string
    {
        $path = rtrim($path, '/') ?: '/';
        foreach (self::SECTIONS as $key => $section) {
            foreach ($section['prefixes'] as $prefix) {
                if ($path === $prefix || str_starts_with($path, $prefix . '/')) {
                    return $key;
                }
            }
        }
        return null;
    }

    public static function currentSection(): ?string
    {
        $path = parse_url((string) ($_SERVER['REQUEST_URI'] ?? ''), PHP_URL_PATH);
        return is_string($path) ? self::sectionForPath($path) : null;
    }

    /** Картки розділу, згруповані за змістом (формат той самий, що в AdminNav::groups). */
    public static function groups(string $section): array
    {
        $card = static fn(string $title, string $text, string $url, string $button, string $style = 'btn-outline-secondary'): array
            => ['title' => $title, 'text' => $text, 'url' => $url, 'button' => $button, 'style' => $style];

        if ($section === 'manage') {
            return [
                ['title' => 'Проєкти', 'cards' => [
                    $card('Проєкти', 'Проєкти підрозділу: зміна статусу й незворотне видалення (власних проєктів і тих, де всі учасники — з вашого підрозділу).', '/unit/projects', 'Керувати проєктами', 'btn-outline-danger'),
                ]],
                ['title' => 'Задачі (усі проєкти підрозділу)', 'cards' => [
                    $card('📝 Задачі', 'Список задач проєктів підрозділу з фільтрами.', '/tasks', 'Відкрити задачі'),
                    $card('📋 Канбан — усі проєкти', 'Канбан-дошка з задачами всіх проєктів підрозділу, згрупована по статусах.', '/unit/board', 'Відкрити дошку'),
                    $card('📊 Гант — усі проєкти', 'Діаграма Ганта з термінами задач усіх проєктів підрозділу на одній шкалі.', '/unit/gantt', 'Відкрити діаграму'),
                    $card('⏱️ Облік часу — усі проєкти', 'Сума годин, розбивка по проєктах і учасниках, список записів по проєктах підрозділу.', '/unit/time', 'Відкрити звіт'),
                ]],
                ['title' => 'Тікети', 'cards' => [
                    $card('🎫 Тікети', 'Тікети підрозділу: перегляд, коментарі, зміна статусу.', '/tickets', 'Відкрити тікети'),
                    $card('Черги тікетів', 'Тікети підрозділу в розрізі черг (лише перегляд: налаштування черг і SLA — в адміністратора системи).', '/unit/queues', 'Переглянути черги', 'btn-outline-primary'),
                    $card('⭐ CSAT — якість обслуговування', 'Оцінки заявників за тікетами підрозділу: середня, по чергах і операторах, останні оцінки.', '/unit/csat', 'Переглянути звіт'),
                ]],
            ];
        }

        return [
            ['title' => 'Користувачі й доступ', 'cards' => [
                $card('Користувачі', 'Користувачі підрозділу (AD і локальні): ролі, активація/деактивація, скидання пароля локальних, зняття блокування.', '/unit/users', 'Керувати користувачами', 'btn-outline-primary'),
            ]],
            ['title' => 'Контроль', 'cards' => [
                $card('📜 Журнал аудиту', 'Дії користувачів підрозділу та події над їхніми обліковими записами — з фільтрами за типом, автором і датою.', '/unit/audit', 'Переглянути журнал'),
            ]],
        ];
    }
}
